package tenantschema

import (
	"bytes"
	"fmt"
	"maps"
	"slices"
	"strconv"
	"strings"

	"github.com/grafana/ai-sdk/ai-gateway/pkg/extension/tenanttype"
)

// MembersFile is the CUE file, relative to the Gateway module root, that
// holds the generated members.
const MembersFile = "kinds/middleware_members.cue"

const membersHeader = `// Code generated by pkg/internal/tenantschema/cmd/members. DO NOT EDIT.
// Regenerate with: mise run generate-ai-gateway-kinds

package kinds

// middlewareMembers holds one optional Middleware spec member per public
// tenant type with configuration.
`

// Members projects every type and checks that each projection is structural
// and keeps the type's example through pruning.
func Members(types []tenanttype.Type) ([]Member, error) {
	var members []Member
	for _, tenantType := range types {
		member, ok, err := Project(tenantType)
		if err != nil {
			return nil, err
		}
		if !ok {
			continue
		}
		s, err := Structural([]Member{member})
		if err != nil {
			return nil, fmt.Errorf("tenant type %q: %w", tenantType.Name, err)
		}
		if err := RoundTrip(s, tenantType.Name, member.Name, tenantType.Example); err != nil {
			return nil, err
		}
		members = append(members, member)
	}
	return members, nil
}

// Render returns the members file for types.
func Render(types []tenanttype.Type) ([]byte, error) {
	members, err := Members(types)
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString(membersHeader)
	if len(members) == 0 {
		out.WriteString("middlewareMembers: {}\n")
		return out.Bytes(), nil
	}
	out.WriteString("middlewareMembers: {\n")
	for _, member := range members {
		writeField(&out, 1, member.Name, false, member.Schema)
	}
	out.WriteString("}\n")
	return out.Bytes(), nil
}

func writeField(out *bytes.Buffer, depth int, name string, required bool, node *Node) {
	indent := strings.Repeat("\t", depth)
	if description := strings.TrimSpace(node.Description); description != "" {
		for line := range strings.SplitSeq(description, "\n") {
			fmt.Fprintf(out, "%s// %s\n", indent, strings.TrimSpace(line))
		}
	}
	marker := "?"
	if required {
		marker = ""
	}
	fmt.Fprintf(out, "%s%s%s: %s\n", indent, strconv.Quote(name), marker, expression(node, depth))
}

func expression(node *Node, depth int) string {
	switch node.Type {
	case TypeString:
		return "string"
	case TypeInteger:
		return "int"
	case TypeNumber:
		return "number"
	case TypeBoolean:
		return "bool"
	case TypeArray:
		return "[..." + expression(node.Items, depth) + "]"
	}
	var out bytes.Buffer
	out.WriteString("{\n")
	for _, name := range slices.Sorted(maps.Keys(node.Properties)) {
		writeField(&out, depth+1, name, slices.Contains(node.Required, name), node.Properties[name])
	}
	out.WriteString(strings.Repeat("\t", depth) + "}")
	return out.String()
}
